export type VaultTextKey = keyof typeof copy;

/** This locale lookup deliberately does not access protected user preferences. */
export function vaultLocale(preferred?: string): UiLanguage {
  let language = preferred;
  if (!language) {
    try {
      language =
        typeof chrome !== 'undefined'
          ? chrome.i18n?.getUILanguage?.()
          : undefined;
    } catch {
      // Browser locale may be unavailable in previews or an invalidated extension.
    }
  }
  language ||= typeof navigator !== 'undefined' ? navigator.language : 'en';
  const base = language.toLowerCase().split(/[-_]/)[0];
  return languages.find((candidate) => candidate === base) ?? 'en';
}

export function vaultText(language: UiLanguage, key: VaultTextKey): string {
  return copy[key][languages.indexOf(language)] ?? copy[key][0];
}
