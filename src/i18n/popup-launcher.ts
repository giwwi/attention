export type PopupLauncherTextKey = keyof typeof copy;
export function popupLauncherText(
  language: UiLanguage,
  key: PopupLauncherTextKey,
): string {
  return copy[key][languages.indexOf(language)] ?? copy[key][0];
}
export function translatePopupLauncher(language: UiLanguage): void {
  for (const element of document.querySelectorAll<HTMLElement>(
    '[data-launcher-i18n]',
  )) {
    const key = element.dataset.launcherI18n as PopupLauncherTextKey;
    if (key in copy) element.textContent = popupLauncherText(language, key);
  }
}
