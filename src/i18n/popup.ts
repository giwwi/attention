export type PopupTextKey = keyof typeof copy;

export function popupText(
  language: UiLanguage,
  key: PopupTextKey,
  variables: Record<string, string | number> = {},
): string {
  let value: string = copy[key][languages.indexOf(language)] ?? copy[key][0];
  for (const [name, replacement] of Object.entries(variables))
    value = value.replaceAll(`{${name}}`, String(replacement));
  return value;
}

export function translatePopup(
  language = normalizeUiLanguage(document.documentElement.lang),
): void {
  for (const element of document.querySelectorAll<HTMLElement>(
    '[data-popup-i18n]',
  )) {
    const key = element.dataset.popupI18n as PopupTextKey;
    if (key in copy) element.textContent = popupText(language, key);
  }
  for (const element of document.querySelectorAll<HTMLElement>(
    '[data-popup-aria]',
  )) {
    const key = element.dataset.popupAria as PopupTextKey;
    if (key in copy)
      element.setAttribute('aria-label', popupText(language, key));
  }
}
