export function readingPlanText(
  language: UiLanguage,
  key: keyof Copy,
  values: Record<string, string | number> = {},
): string {
  return copy[language][key].replace(/\{(\w+)\}/g, (match, name: string) =>
    values[name] === undefined ? match : String(values[name]),
  );
}
